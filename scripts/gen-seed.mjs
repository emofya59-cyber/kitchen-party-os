// Generates supabase/seed.sql from the same demo data the frontend uses offline.
// Usage: node scripts/gen-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { DEMO } from '../src/mock/demo-data.ts'

const plan = JSON.parse(readFileSync(new URL('../src/mock/woodlands-plan.json', import.meta.url), 'utf8'))
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`
const { ids, users, hostOrg, vendors, event, guests, payments } = DEMO
const HOSTED = process.argv.includes('--hosted')
const out = []
const createdBy = () => (HOSTED ? 'null' : q(users[0].id))

out.push(`-- =====================================================================
-- Kitchen Party OS — demo seed (Lusaka). GENERATED by scripts/gen-seed.mjs.
-- All prices are EXAMPLE ESTIMATES, not vendor quotes. Phone numbers are fake.
-- ${HOSTED ? 'HOSTED variant: no auth.users/org_members rows; demo event flagged is_demo (readable by anon via RLS). Requires 0002.' : 'Runs on \`supabase db reset\` (local) as postgres; bypasses RLS.'}
-- =====================================================================
begin;
`)

if (!HOSTED) out.push(`-- Demo auth users (local dev only; on hosted Supabase create users via Auth instead)
insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at)
values
${users.map((u) => `  ('00000000-0000-0000-0000-000000000000', ${q(u.id)}, 'authenticated', 'authenticated', ${q(u.email)}, crypt('demo-password-123', gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}', ${q(JSON.stringify({ full_name: u.name }))}, now(), now())`).join(',\n')}
on conflict (id) do nothing;
`)

const orgs = [hostOrg, ...vendors.map((v) => v.org)]
out.push(`insert into public.orgs (id, type, name, slug, phone, email, area) values
${orgs.map((o) => `  (${q(o.id)}, ${q(o.type)}, ${q(o.name)}, ${q(o.slug)}, ${q(o.phone)}, ${q(o.email)}, ${q(o.area)})`).join(',\n')};
`)

if (!HOSTED) out.push(`insert into public.org_members (org_id, user_id, role) values
${users.map((u) => `  (${q(u.org_id)}, ${q(u.id)}, 'owner')`).join(',\n')};
`)

out.push(`insert into public.vendors (id, org_id, display_name, category, service_areas, whatsapp, rating, bio) values
${vendors.map((v) => `  (${q(v.id)}, ${q(v.org.id)}, ${q(v.org.name)}, ${q(v.category)}, ${arr(v.service_areas)}, ${q(v.org.phone)}, ${q(v.rating)}, ${q(v.bio)})`).join(',\n')};
`)

out.push(`insert into public.vendor_catalog_items (vendor_id, org_id, name, category, unit, price_zmw, min_qty, serves) values
${vendors.flatMap((v) => v.catalog.map((c) => `  (${q(v.id)}, ${q(v.org.id)}, ${q(c.name)}, ${c.category ? `${q(c.category)}` : 'null'}, ${q(c.unit)}, ${q(c.price_zmw)}, ${q(c.min_qty ?? 1)}, ${q(c.serves ?? null)})`)).join(',\n')};
`)

out.push(`insert into public.events (id, org_id, title, event_type, status, starts_at, ends_at, venue, area, guest_target, budget_zmw, brief, created_by) values
  (${q(event.id)}, ${q(hostOrg.id)}, ${q(event.title)}, 'kitchen_party', 'planning', ${q(event.starts_at)}, ${q(event.ends_at)}, ${q(event.venue)}, ${q(event.area)}, ${event.guest_target}, ${event.budget_zmw}, ${q(event.brief)}, ${createdBy()});
`)

const vByRef = Object.fromEntries(vendors.map((v) => [v.org.slug, v]))
out.push(`insert into public.event_vendors (event_id, org_id, vendor_id, service, status, quoted_zmw, notes) values
${plan.vendor_assignments.map((a) => `  (${q(event.id)}, ${q(hostOrg.id)}, ${q(vByRef[a.vendor_ref].id)}, ${q(a.service)}, ${q(vByRef[a.vendor_ref].booking_status)}, ${a.estimated_zmw}, ${q(a.scope)})`).join(',\n')};
`)

out.push(`insert into public.menu_items (event_id, org_id, vendor_id, name, category, quantity, unit, per_guest, unit_cost_zmw, notes, sort_order) values
${plan.menu.map((m, i) => `  (${q(event.id)}, ${q(hostOrg.id)}, ${q(vByRef[m.vendor_ref]?.id ?? null)}, ${q(m.name)}, ${q(m.category)}, ${m.quantity}, ${q(m.unit)}, ${q(m.per_guest_qty)}, ${m.unit_cost_zmw}, ${q(m.notes)}, ${i + 1})`).join(',\n')};
`)

out.push(`-- ${guests.length} guest rows; party_size sums to ${guests.reduce((s, g) => s + g.party_size, 0)} people
insert into public.guests (id, event_id, org_id, full_name, phone, rsvp_status, party_size, guest_group) values
${guests.map((g) => `  (${q(g.id)}, ${q(event.id)}, ${q(hostOrg.id)}, ${q(g.full_name)}, ${q(g.phone)}, ${q(g.rsvp_status)}, ${g.party_size}, ${q(g.guest_group)})`).join(',\n')};
`)

out.push(`-- provider_ref values are DEMO placeholders, not real Elicate Pay references
insert into public.payments (id, event_id, org_id, vendor_id, purpose, amount_zmw, status, provider_ref, payer_phone, payer_network, paid_at, created_by) values
${payments.map((p) => `  (${q(p.id)}, ${q(event.id)}, ${q(hostOrg.id)}, ${q(vByRef[p.vendor_ref].id)}, 'deposit', ${p.amount_zmw}, ${q(p.status)}, ${q(p.provider_ref)}, ${q(p.payer_phone)}, ${q(p.payer_network)}, ${q(p.paid_at)}, ${createdBy()})`).join(',\n')};
`)

out.push(`insert into public.plan_revisions (id, event_id, org_id, revision_no, kind, instruction, plan, guest_count, total_zmw, model, created_by) values
  (${q(ids.revision1)}, ${q(event.id)}, ${q(hostOrg.id)}, 1, 'initial', ${q(event.brief)}, ${q(JSON.stringify(plan))}::jsonb, ${plan.event.guest_count}, ${plan.cost_breakdown.total_zmw}, 'seed-example', ${createdBy()});

update public.events set current_revision_id = ${q(ids.revision1)}${HOSTED ? ', is_demo = true' : ''} where id = ${q(event.id)};
${HOSTED ? bridgeSeed() : ''}

commit;
`)

const target = HOSTED ? 'seed.hosted.sql' : 'seed.sql'
writeFileSync(new URL(`../supabase/${target}`, import.meta.url), out.join('\n'))
console.log(`wrote supabase/${target}`)

