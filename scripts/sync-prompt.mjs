// Regenerates supabase/functions/_shared/planner-prompt.ts from prompts/planner.md
// and refreshes the example output block from src/mock/woodlands-plan.json.
import { readFileSync, writeFileSync } from 'node:fs'

const mdUrl = new URL('../prompts/planner.md', import.meta.url)
let md = readFileSync(mdUrl, 'utf8')
const example = readFileSync(new URL('../src/mock/woodlands-plan.json', import.meta.url), 'utf8').trim()

md = md.replace(/<!-- BEGIN:EXAMPLE -->[\s\S]*?<!-- END:EXAMPLE -->/, `<!-- BEGIN:EXAMPLE -->\n\`\`\`json\n${example}\n\`\`\`\n<!-- END:EXAMPLE -->`)
writeFileSync(mdUrl, md)

const block = (name) => {
  const m = md.match(new RegExp(`<!-- BEGIN:${name} -->\\s*\`\`\`\\w*\\n([\\s\\S]*?)\\n\`\`\`\\s*<!-- END:${name} -->`))
  if (!m) throw new Error(`block ${name} not found in planner.md`)
  return m[1]
}
const schema = JSON.parse(block('SCHEMA')) // throws if invalid JSON

const ts = `// GENERATED by scripts/sync-prompt.mjs from prompts/planner.md. Do not edit by hand.
export const PLANNER_SYSTEM_PROMPT = ${JSON.stringify(block('SYSTEM'))}

export const PLANNER_REVISION_PROMPT = ${JSON.stringify(block('REVISION'))}

export const PLAN_JSON_SCHEMA = ${JSON.stringify(schema, null, 2)} as const
`
writeFileSync(new URL('../supabase/functions/_shared/planner-prompt.ts', import.meta.url), ts)
console.log('synced planner prompt → supabase/functions/_shared/planner-prompt.ts')
